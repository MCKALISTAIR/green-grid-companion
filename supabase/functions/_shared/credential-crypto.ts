// Application-layer encryption for third-party API keys (e.g. Octopus Energy).
//
// Keys are encrypted with AES-256-GCM inside edge functions before they are
// written to Postgres. The encryption key is derived from the edge function
// secret `OCTOPUS_CREDENTIALS_KEY` and never stored in the database,
// so a database dump / leaked SQL access alone does not reveal API keys.
// The owning user's id is bound as additional authenticated data (AAD), so a
// ciphertext copied onto another user's row will fail to decrypt.
//
// Runtime-agnostic (Web Crypto only) so it can be unit tested from Vitest.

const VERSION = 'v1';

function bytesToBase64(bytes: Uint8Array): string {
  let bin = '';
  for (let i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
  return btoa(bin);
}

function base64ToBytes(b64: string) {
  const bin = atob(b64);
  const out = new Uint8Array(new ArrayBuffer(bin.length));
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

/** Minimum length for a passphrase-style OCTOPUS_CREDENTIALS_KEY. */
export const MIN_CREDENTIAL_SECRET_LENGTH = 32;

const HKDF_INFO = new TextEncoder().encode('gridsense/octopus-credentials/v1');

function tryDecodeBase64Key(value: string) {
  if (!/^[A-Za-z0-9+/]{43}=$/.test(value)) return null;
  try {
    const raw = base64ToBytes(value);
    return raw.length === 32 ? raw : null;
  } catch {
    return null;
  }
}

/**
 * Import the credential encryption key from the OCTOPUS_CREDENTIALS_KEY secret.
 *
 * Accepts either
 *  - a base64-encoded 32-byte key (e.g. `openssl rand -base64 32`), used as-is, or
 *  - any random string of at least 32 characters (e.g. a 64-character password
 *    generated by a password manager on a phone), from which a 256-bit AES key
 *    is derived with HKDF-SHA-256. Derivation is deterministic, so the same
 *    secret always yields the same key.
 */
export async function importCredentialKey(secret: string | undefined | null): Promise<CryptoKey> {
  const value = (secret ?? '').trim();
  if (!value) {
    throw new Error('OCTOPUS_CREDENTIALS_KEY is not configured');
  }

  const raw = tryDecodeBase64Key(value);
  if (raw) {
    return crypto.subtle.importKey('raw', raw, { name: 'AES-GCM' }, false, ['encrypt', 'decrypt']);
  }

  if (value.length < MIN_CREDENTIAL_SECRET_LENGTH) {
    throw new Error(`OCTOPUS_CREDENTIALS_KEY must be at least ${MIN_CREDENTIAL_SECRET_LENGTH} characters (or a base64 32-byte key)`);
  }

  const ikm = await crypto.subtle.importKey('raw', new TextEncoder().encode(value), 'HKDF', false, ['deriveKey']);
  return crypto.subtle.deriveKey(
    { name: 'HKDF', hash: 'SHA-256', salt: new Uint8Array(new ArrayBuffer(32)), info: HKDF_INFO },
    ikm,
    { name: 'AES-GCM', length: 256 },
    false,
    ['encrypt', 'decrypt'],
  );
}

/** Encrypt `plaintext` for `userId`. Output format: `v1.<iv b64>.<ciphertext b64>`. */
export async function encryptCredential(plaintext: string, key: CryptoKey, userId: string): Promise<string> {
  const iv = crypto.getRandomValues(new Uint8Array(new ArrayBuffer(12)));
  const ct = await crypto.subtle.encrypt(
    { name: 'AES-GCM', iv, additionalData: new TextEncoder().encode(userId) },
    key,
    new TextEncoder().encode(plaintext),
  );
  return `${VERSION}.${bytesToBase64(iv)}.${bytesToBase64(new Uint8Array(ct))}`;
}

/** Decrypt a value produced by `encryptCredential` for the same `userId`. Throws on tamper/mismatch. */
export async function decryptCredential(payload: string, key: CryptoKey, userId: string): Promise<string> {
  const parts = payload.split('.');
  if (parts.length !== 3 || parts[0] !== VERSION) {
    throw new Error('Unsupported credential ciphertext format');
  }
  const iv = base64ToBytes(parts[1]);
  const ct = base64ToBytes(parts[2]);
  const pt = await crypto.subtle.decrypt(
    { name: 'AES-GCM', iv, additionalData: new TextEncoder().encode(userId) },
    key,
    ct,
  );
  return new TextDecoder().decode(pt);
}

/** Non-secret hint shown to the user (last 4 characters only). */
export function apiKeyHint(apiKey: string): string {
  const trimmed = apiKey.trim();
  return trimmed.length >= 4 ? trimmed.slice(-4) : '';
}
